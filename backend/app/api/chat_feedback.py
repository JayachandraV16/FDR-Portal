"""Copilot answer feedback.

  POST /chat/feedback            rate one answer (any signed-in role)
  GET  /chat/feedback/summary    counts for administrators

A submission carries the rating, an optional FIXED reason, and facts about the answer (kind, source, provider,
language, page). It never carries, and the table never stores, the question, the answer or any free text. The
client's `reply_id` makes a repeated submission (a double click, a retry after a timeout) land on the existing row:
the first rating for a reply is kept and the response says it was a duplicate. Each user has a small rate limit.

The table comes from migration 0007. Until that migration has been applied to a database, these endpoints answer
503 "not available" and nothing is stored: feedback is never pretended to be saved.
"""

import uuid
from collections import Counter
from datetime import timedelta
from typing import Literal

from fastapi import APIRouter, Depends, HTTPException, Query, Response
from pydantic import BaseModel, ConfigDict, model_validator
from sqlalchemy import inspect, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.api.chat import Language, Page, RateLimiter
from app.api.deps import AuthContext, require_authenticated, require_roles
from app.db import get_db
from app.models import ChatFeedback, Role
from app.timeutil import utcnow

router = APIRouter(tags=["chat"])
limiter = RateLimiter(limit=30, window=600)  # ratings per user per ten minutes
admin_only = require_roles(Role.ADMIN)
RETENTION_DAYS = 90
Reason = Literal["incorrect", "unclear", "incomplete", "not_relevant", "other"]


class FeedbackRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    reply_id: uuid.UUID  # generated by the browser for each answer it shows; makes a repeat harmless
    rating: Literal["helpful", "not_helpful"]
    reason: Reason | None = None
    kind: Literal["help", "records", "unknown"]
    source: Literal["built-in", "llm"]
    provider: Literal["gemini", "openai_compatible"] | None = None
    language: Language = "en"
    page: Page | None = None

    @model_validator(mode="after")
    def _consistent(self) -> "FeedbackRequest":
        if self.reason is not None and self.rating != "not_helpful":
            raise ValueError("A reason can only be given with 'not_helpful'")
        if self.source == "built-in" and self.provider is not None:
            raise ValueError("A built-in answer has no provider")
        return self


class FeedbackOut(BaseModel):
    recorded: bool
    duplicate: bool
    rating: Literal["helpful", "not_helpful"]


class FeedbackSummary(BaseModel):
    available: bool
    note: str | None
    retention_days: int
    window_days: int
    total: int
    helpful: int
    not_helpful: int
    by_reason: dict[str, int]
    by_kind: dict[str, int]
    by_source: dict[str, int]
    by_language: dict[str, int]
    by_page: dict[str, int]


def _ready(db: Session) -> bool:
    return inspect(db.get_bind()).has_table(ChatFeedback.__tablename__)


def _word(rating: int) -> Literal["helpful", "not_helpful"]:
    return "helpful" if rating == 1 else "not_helpful"


@router.post("/chat/feedback", response_model=FeedbackOut)
def submit_feedback(
    body: FeedbackRequest, response: Response, db: Session = Depends(get_db), auth: AuthContext = Depends(require_authenticated),
) -> FeedbackOut:
    response.headers["Cache-Control"] = "no-store"
    if not _ready(db):
        raise HTTPException(status_code=503, detail="Feedback is not available on this server yet.")
    if not limiter.allow(auth.user.id):
        raise HTTPException(status_code=429, detail="You are sending feedback too quickly. Please wait a moment.")
    existing = db.scalar(select(ChatFeedback).where(ChatFeedback.user_id == auth.user.id, ChatFeedback.reply_id == body.reply_id))
    if existing is not None:
        return FeedbackOut(recorded=True, duplicate=True, rating=_word(existing.rating))
    row = ChatFeedback(
        user_id=auth.user.id, rating=1 if body.rating == "helpful" else -1, reason_code=body.reason, reply_kind=body.kind, source=body.source,
        provider=body.provider, language=body.language, page=body.page, reply_id=body.reply_id,
    )
    db.add(row)
    try:
        db.commit()
    except IntegrityError:  # two submissions for the same reply raced; the other one won
        db.rollback()
        existing = db.scalar(select(ChatFeedback).where(ChatFeedback.user_id == auth.user.id, ChatFeedback.reply_id == body.reply_id))
        if existing is None:
            raise HTTPException(status_code=409, detail="The feedback could not be recorded.") from None
        return FeedbackOut(recorded=True, duplicate=True, rating=_word(existing.rating))
    return FeedbackOut(recorded=True, duplicate=False, rating=body.rating)


@router.get("/chat/feedback/summary", response_model=FeedbackSummary)
def feedback_summary(
    response: Response, days: int = Query(RETENTION_DAYS, description="Window in days: 7, 30 or 90"), db: Session = Depends(get_db),
    auth: AuthContext = Depends(admin_only),
) -> FeedbackSummary:
    response.headers["Cache-Control"] = "no-store"
    if days not in (7, 30, RETENTION_DAYS):
        raise HTTPException(status_code=422, detail="days must be 7, 30 or 90")
    empty = dict(retention_days=RETENTION_DAYS, window_days=days, total=0, helpful=0, not_helpful=0, by_reason={}, by_kind={}, by_source={}, by_language={}, by_page={})
    if not _ready(db):
        return FeedbackSummary(available=False, note="Feedback is not stored on this server yet: its database migration has not been applied.", **empty)
    rows = db.execute(
        select(ChatFeedback.rating, ChatFeedback.reason_code, ChatFeedback.reply_kind, ChatFeedback.source, ChatFeedback.language, ChatFeedback.page)
        .where(ChatFeedback.created_at >= utcnow() - timedelta(days=days))
    ).all()
    count = lambda index: dict(Counter(r[index] or "none" for r in rows))  # noqa: E731
    return FeedbackSummary(
        available=True, note=None, retention_days=RETENTION_DAYS, window_days=days, total=len(rows), helpful=sum(1 for r in rows if r[0] == 1),
        not_helpful=sum(1 for r in rows if r[0] == -1), by_reason={k: v for k, v in count(1).items() if k != "none"}, by_kind=count(2), by_source=count(3),
        by_language=count(4), by_page=count(5),
    )
