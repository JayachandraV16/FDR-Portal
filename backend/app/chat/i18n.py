def release_note(language: str, *, accepted: bool, matured: bool, date_iso: str) -> str:
    if not accepted:
        return "केवल स्वीकृत FDR ही रिलीज़ की जा सकती है।" if language == "hi" else "फक्त स्वीकृत FDR रिलीज करता येते."
    if not matured:
        return (f"अभी परिपक्व नहीं हुई: परिपक्वता तिथि {date_iso} है।" if language == "hi"
                else f"अद्याप परिपक्व झालेली नाही: परिपक्वता तारीख {date_iso} आहे.")
    return "परिपक्व और स्वीकृत: रिलीज़ अनुरोध के लिए पात्र।" if language == "hi" else "परिपक्व आणि स्वीकृत: रिलीज विनंतीसाठी पात्र."


