def counts_text(language: str, *, n: int, total: int, status: str | None, counts: dict[str, int]) -> str:
    labels = STATUS_LABELS[language]
    if status:
        if language == "hi":
            if status == "SUBMITTED":
                return f"आप {n} FDR देख सकते हैं जो समीक्षा के लिए लंबित हैं (स्थिति Submitted)।"
            return f"आप {n} FDR देख सकते हैं जिनकी स्थिति {labels[status]} है।"
        if status == "SUBMITTED":
            return f"तुम्ही {n} FDR पाहू शकता ज्या समीक्षेसाठी प्रलंबित आहेत (स्थिती Submitted)."
        return f"तुम्ही {n} FDR पाहू शकता ज्यांची स्थिती {labels[status]} आहे."
    breakdown = ", ".join(f"{counts[s]} {labels[s]}" for s in labels if s in counts)
    if language == "hi":
        return f"आप कुल {total} FDR देख सकते हैं" + (f": {breakdown}।" if breakdown else "।")
    return f"तुम्ही एकूण {total} FDR पाहू शकता" + (f": {breakdown}." if breakdown else ".")


def maturing_text(language: str, *, total: int, shown: int, days: int, overdue: int) -> str:
    if language == "hi":
        text = (f"आप जो FDRs देख सकते हैं उनमें से कोई भी अगले {days} दिनों में परिपक्व नहीं हो रही।" if total == 0
                else f"आप जो FDRs देख सकते हैं उनमें से {total} अगले {days} दिनों में परिपक्व हो रही हैं।")
        if total > shown:
            text += f" सबसे नज़दीकी {shown} सूचीबद्ध हैं।"
        if overdue:
            text += f" {overdue} सक्रिय FDR पहले ही परिपक्वता तिथि पार कर चुकी हैं (Alerts देखें)।"
        return text
    text = (f"तुम्ही पाहू शकता त्यापैकी कोणतीही FDR पुढील {days} दिवसांत परिपक्व होत नाही." if total == 0
            else f"तुम्ही पाहू शकता त्यापैकी {total} FDR पुढील {days} दिवसांत परिपक्व होत आहेत.")
    if total > shown:
        text += f" सर्वात जवळच्या {shown} दिल्या आहेत."
    if overdue:
        text += f" {overdue} सक्रिय FDR आधीच परिपक्वता तारीख ओलांडून गेल्या आहेत (Alerts पहा)."
    return text


